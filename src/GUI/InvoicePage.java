    private void setupInvoiceAutoCalculation() {
        String priceText = invoPriceFormattedTextField.getText().trim();
        String paymentText = invoPayentFormattedTextField.getText().trim();

        if (priceText.isEmpty() || paymentText.isEmpty()) {
            invoBalanceFormattedTextField.setText("0.00");
            return;
        }

        try {
            double price = Double.parseDouble(priceText);
            double payment = Double.parseDouble(paymentText);

            double balance = payment - price;
            invoBalanceFormattedTextField.setText(String.format("%.2f", balance));
            invoBalanceFormattedTextField.setForeground(balance < 0 ? java.awt.Color.RED : java.awt.Color.BLACK);

        } catch (NumberFormatException e) {
            invoBalanceFormattedTextField.setText("0.00");
        }
    }

    private void addInvoice() {

        try {
            // ---------- VALIDATION ----------
            String bookingId = invoBookIdTextField.getText().trim();
            if (bookingId.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please select a booking");
                return;
            }

            int workRow = invoiceMassageTable.getSelectedRow();
            if (workRow == -1) {
                JOptionPane.showMessageDialog(this, "Please select a work");
                return;
            }

            String priceText = invoPriceFormattedTextField.getText().trim();
            String paymentText = invoPayentFormattedTextField.getText().trim();

            if (priceText.isEmpty() || paymentText.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Enter price and payment");
                return;
            }

            if (!isValidDouble(priceText) || !isValidDouble(paymentText)) {
                JOptionPane.showMessageDialog(this, "Price and Payment must be numeric");
                return;
            }

            double price = Double.parseDouble(priceText);
            double payment = Double.parseDouble(paymentText);
            double balance = payment - price;

            invoBalanceFormattedTextField.setText(String.format("%.2f", balance));
            if (balance < 0) {
                invoBalanceFormattedTextField.setForeground(Color.RED);
                JOptionPane.showMessageDialog(this, "Payment is not enough");
                return;
            } else {
                invoBalanceFormattedTextField.setForeground(Color.BLACK);
            }

            // ---------- OPEN SESSION ----------
            session = HibernateUtil.getSessionFactory().openSession();

            Booking booking = session.get(Booking.class, bookingId);
            if (booking == null) {
                JOptionPane.showMessageDialog(this, "Invalid Booking ID");
                return;
            }

            String workName = invoiceMassageTable.getValueAt(workRow, 1).toString();
            CustomerWantCategory category = session.createQuery(
                    "FROM CustomerWantCategory WHERE works = :work",
                    CustomerWantCategory.class)
                    .setParameter("work", workName)
                    .uniqueResult();

            if (category == null) {
                JOptionPane.showMessageDialog(this, "Invalid work selection");
                return;
            }

            // ---------- CREATE OBJECTS (NOT SAVED YET) ----------
            InvoiceItem item = new InvoiceItem();
            item.setBooking_id(booking);
            item.setCus_want_category_id(category);

            Invoice invoice = new Invoice();
            invoice.setId(IDGenerator.generateId("INV", "Invoice"));
            invoice.setPrice(price);
            invoice.setInvoice_item_id(item);

            // ---------- PRINT FIRST ----------
            boolean printed = printInvoice(invoice, booking, category, price, payment, balance);

            if (!printed) {
                JOptionPane.showMessageDialog(this, "Print cancelled. Invoice not saved.");
                clearInvoiceFields();
                return;
            }

            // ---------- START TRANSACTION ----------
            transaction = session.beginTransaction();

            session.save(item);
            session.save(invoice);

            WorkingStatus complete = session.createQuery(
                    "FROM WorkingStatus WHERE status = 'Complete'",
                    WorkingStatus.class)
                    .uniqueResult();

            booking.setWorking_status_id(complete);
            session.update(booking);

            transaction.commit();

            // ---------- UI UPDATE ----------
//            addInvoiceRow(invoice, booking, category, price, payment, balance);
            JOptionPane.showMessageDialog(this, "Invoice Printed Successfully");
            clearInvoiceFields();

        } catch (Exception e) {
            if (transaction != null && transaction.isActive()) {
                transaction.rollback();
            }
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());

        } finally {
            if (session != null) {
                session.close();
            }
        }
    }

    private boolean printInvoice(Invoice invoice, Booking booking,
            CustomerWantCategory category,
            double price, double payment, double balance) {

        JTextArea area = new JTextArea(
                "------ SALOON INVOICE ------\n\n"
                + "Invoice No : " + invoice.getId() + "\n"
                + "Booking ID : " + booking.getId() + "\n"
                + "Customer   : "
                + booking.getCustomer_id().getFname() + " "
                + booking.getCustomer_id().getLname() + "\n"
                + "Work       : " + category.getWorks() + "\n\n"
                + "Price      : " + price + "\n"
                + "Payment    : " + payment + "\n"
                + "Balance    : " + balance + "\n\n"
                + "------------------------------"
                + "----Powered By @Thanuja2003 Software Solution----"
        );

        try {
            return area.print(null, null, true, null, null, true);
        } catch (PrinterException e) {
            JOptionPane.showMessageDialog(this, "Print failed: " + e.getMessage());
            return false;
        }
    }

