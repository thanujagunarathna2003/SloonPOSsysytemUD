    private void loadInvoiceTable() {
        try (Session session = HibernateUtil.getSessionFactory().openSession()) {

            // --- Fetch all invoices with their related data ---
            List<Invoice> invoiceList = session.createQuery(
                    "FROM Invoice i ORDER BY i.id ASC", Invoice.class
            ).list();

            DefaultTableModel model = (DefaultTableModel) invoiceTable.getModel();
            model.setRowCount(0); // Clear existing rows

            for (Invoice inv : invoiceList) {
                InvoiceItem item = inv.getInvoice_item_id();
                Booking booking = item.getBooking_id();
                CustomerWantCategory category = item.getCus_want_category_id();
                double price = inv.getPrice();

                Vector<Object> row = new Vector<>();
                row.add(inv.getId());
                row.add(category.getWorks());
                row.add(booking.getId());
                row.add(price);

                model.addRow(row);
            }

            //Table Center
            DefaultTableCellRenderer centerRenderer = new DefaultTableCellRenderer();
            centerRenderer.setHorizontalAlignment(DefaultTableCellRenderer.CENTER);
            for (int i = 0; i < invoiceTable.getColumnCount(); i++) {
                invoiceTable.getColumnModel().getColumn(i).setCellRenderer(centerRenderer);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading invoices: " + e.getMessage());
            e.printStackTrace();
        }
    }

