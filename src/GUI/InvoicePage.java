    private void loadBookingTable() {
        try (Session session = HibernateUtil.getSessionFactory().openSession()) {

            List<Booking> bookingList = session.createQuery(
                    "FROM Booking b WHERE b.date = :today AND b.working_status_id.id = :statusId ORDER BY b.id ASC",
                    Booking.class
            )
                    .setParameter("statusId", 1)
                    .setParameter("today", today)
                    .list();

            DefaultTableModel model = (DefaultTableModel) invoiceCustmerTable.getModel();
            model.setRowCount(0);

            for (Booking b : bookingList) {
                String fullName = b.getCustomer_id().getFname() + " " + b.getCustomer_id().getLname();

                Vector<Object> row = new Vector<>();
                row.add(b.getId());
                row.add(b.getCustomer_id().getId());
                row.add(fullName);
                row.add(b.getDate());
                row.add(b.getStart_time());
                row.add(b.getEnd_time());
                row.add(b.getCustomer_id().getMobile());
                row.add(b.getBooking_status_id().getBooking_st());
                row.add(b.getWorking_status_id().getStatus());

                model.addRow(row);
            }

            //Table Center
            DefaultTableCellRenderer centerRenderer = new DefaultTableCellRenderer();
            centerRenderer.setHorizontalAlignment(DefaultTableCellRenderer.CENTER);
            for (int i = 0; i < invoiceCustmerTable.getColumnCount(); i++) {
                invoiceCustmerTable.getColumnModel().getColumn(i).setCellRenderer(centerRenderer);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading bookings: " + e.getMessage());
            e.printStackTrace();
        }
    }

