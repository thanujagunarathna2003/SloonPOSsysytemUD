    private void addCustomer() {

        Transaction transaction = null;
        Session session = null;

        try {
            // --- Confirm Action ---
            int confirm = JOptionPane.showConfirmDialog(
                    this,
                    "Do you want to add this customer?",
                    "Confirm Add",
                    JOptionPane.YES_NO_OPTION,
                    JOptionPane.QUESTION_MESSAGE
            );

            if (confirm != JOptionPane.YES_OPTION) {
                return;
            }

            // --- Collect UI Data ---
            String fname = firstNameTextField.getText().trim();
            String lname = lastNameTextField.getText().trim();
            String mobile = mobileTextField.getText().trim();
            String genderName = (String) genderComboBox.getSelectedItem();
            String ageStatusName = (String) ageComboBox.getSelectedItem();

            // --- Validate Required Fields ---
            if (fname.isEmpty() || lname.isEmpty() || mobile.isEmpty()) {
                JOptionPane.showMessageDialog(this, " Please fill all required fields.");
                return;
            }

            if (genderName == null || ageStatusName == null
                    || genderName.equals("Select") || ageStatusName.equals("Select")) {
                JOptionPane.showMessageDialog(this, " Please select Gender and Age Status.");
                return;
            }

            // --- Start Hibernate Session ---
            session = HibernateUtil.getSessionFactory().openSession();
            transaction = session.beginTransaction();

            // --- Duplicate Mobile Check ---
            CriteriaBuilder cb = session.getCriteriaBuilder();
            CriteriaQuery<Long> cq = cb.createQuery(Long.class
            );
            Root<Customer> root = cq.from(Customer.class
            );

            cq.select(cb.count(root))
                    .where(cb.equal(root.get("mobile"), mobile));

            Long count = session.createQuery(cq).getSingleResult();

            if (count > 0) {
                JOptionPane.showMessageDialog(this, " Mobile number already exists!");
                transaction.rollback();
                return;

            }

            // --- Fetch Related Entities ---
            Query<Gender> genderQuery = session.createQuery(
                    "FROM Gender WHERE gender_name = :gender_name", Gender.class
            );
            genderQuery.setParameter("gender_name", genderName);
            Gender gender = genderQuery.uniqueResult();

            Query<AgeStatus> ageQuery = session.createQuery(
                    "FROM AgeStatus WHERE ages_status = :ages_status", AgeStatus.class
            );
            ageQuery.setParameter("ages_status", ageStatusName);
            AgeStatus ageStatus = ageQuery.uniqueResult();

            if (gender == null || ageStatus == null) {
                JOptionPane.showMessageDialog(this, " Invalid Gender or Age Status.");
                transaction.rollback();
                return;
            }

            // --- Create Customer ---
            Customer customer = new Customer();
            customer.setId(IDGenerator.generateId("CUS", "Customer"));
            customer.setFname(fname);
            customer.setLname(lname);
            customer.setMobile(mobile);
            customer.setGender(gender);
            customer.setAgeStatus(ageStatus);

            session.save(customer);
            transaction.commit();

            JOptionPane.showMessageDialog(this, " Customer added successfully!");
            clearAll();
//            loadCustomerTable();

        } catch (Exception e) {
            if (transaction != null && transaction.getStatus().canRollback()) {
                transaction.rollback();
            }
            JOptionPane.showMessageDialog(this, " Error saving customer: " + e.getMessage());
            e.printStackTrace();
        } finally {
            if (session != null) {
                session.close();
            }
        }
    }

    private void updateCustomer() {

        Transaction transaction = null;
        Session session = null;

        try {
            // --- Collect UI Data ---
            String customerId = customerRagisterNoLable.getText().trim();
            String fname = firstNameTextField.getText().trim();
            String lname = lastNameTextField.getText().trim();
            String mobile = mobileTextField.getText().trim();
            String genderName = (String) genderComboBox.getSelectedItem();
            String ageStatusName = (String) ageComboBox.getSelectedItem();

            // --- Validate Inputs ---
            if (customerId.isEmpty()) {
                JOptionPane.showMessageDialog(this, " Please select a customer first.");
                return;
            }

            if (fname.isEmpty() || lname.isEmpty() || mobile.isEmpty()) {
                JOptionPane.showMessageDialog(this, " Please fill all required fields.");
                return;
            }

            if (genderName == null || ageStatusName == null
                    || genderName.equals("Select") || ageStatusName.equals("Select")) {
                JOptionPane.showMessageDialog(this, " Please select Gender and Age Status.");
                return;
            }

            // --- Start Session ---
            session = HibernateUtil.getSessionFactory().openSession();
            transaction = session.beginTransaction();

            // --- Load Existing Customer ---
            Customer customer = session.get(Customer.class,
                    customerId);
            if (customer == null) {
                JOptionPane.showMessageDialog(this, " Customer not found for ID: " + customerId);
                return;
            }

            // --- Check Duplicate Mobile (excluding current customer) ---
            CriteriaBuilder cb = session.getCriteriaBuilder();
            CriteriaQuery<Long> cq = cb.createQuery(Long.class
            );
            Root<Customer> root = cq.from(Customer.class
            );

            cq.select(cb.count(root))
                    .where(
                            cb.and(
                                    cb.equal(root.get("mobile"), mobile),
                                    cb.notEqual(root.get("id"), customerId)
                            )
                    );

            Long count = session.createQuery(cq).getSingleResult();
            if (count > 0) {
                JOptionPane.showMessageDialog(this, " Mobile number already exists!");
                transaction.rollback();
                return;

            }

            // --- Fetch Related Entities ---
            Query<Gender> genderQuery = session.createQuery(
                    "FROM Gender WHERE gender_name = :gender_name", Gender.class
            );
            genderQuery.setParameter("gender_name", genderName);
            Gender gender = genderQuery.uniqueResult();

            Query<AgeStatus> ageQuery = session.createQuery(
                    "FROM AgeStatus WHERE ages_status = :ages_status", AgeStatus.class
            );
            ageQuery.setParameter("ages_status", ageStatusName);
            AgeStatus ageStatus = ageQuery.uniqueResult();

            if (gender == null || ageStatus == null) {
                JOptionPane.showMessageDialog(this, " Invalid Gender or Age Status.");
                transaction.rollback();
                return;
            }

            // --- Check for No Changes ---
            if (customer.getFname().equals(fname)
                    && customer.getLname().equals(lname)
                    && customer.getMobile().equals(mobile)
                    && customer.getGender().equals(gender)
                    && customer.getAgeStatus().equals(ageStatus)) {

                JOptionPane.showMessageDialog(this, " No changes detected. Customer details are the same.");
                clearAll();
                loadCustomerTable();
                return;
            }

            // --- Update Customer ---
            customer.setFname(fname);
            customer.setLname(lname);
            customer.setMobile(mobile);
            customer.setGender(gender);
            customer.setAgeStatus(ageStatus);

            session.update(customer);
            transaction.commit();

            JOptionPane.showMessageDialog(this, " Customer updated successfully!");
            clearAll();
            loadCustomerTable();

        } catch (Exception e) {
            if (transaction != null && transaction.getStatus().canRollback()) {
                transaction.rollback();
            }
            JOptionPane.showMessageDialog(this, " Error updating customer: " + e.getMessage());
            e.printStackTrace();
        } finally {
            if (session != null) {
                session.close();
            }
        }
    }

