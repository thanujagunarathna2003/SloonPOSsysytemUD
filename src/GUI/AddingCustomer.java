    private void customerTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_customerTableMouseClicked
        // TODO add your handling code here:
        addCustometButton.setEnabled(false);
        customerUpdateButton.setEnabled(true);

        int selectedRow = customerTable.getSelectedRow();
        if (selectedRow == -1) {
            return;
        }

        // Adjust index if sorting is active
        selectedRow = customerTable.convertRowIndexToModel(selectedRow);

        DefaultTableModel model = (DefaultTableModel) customerTable.getModel();

        // --- Extract data from table ---
        String customerId = model.getValueAt(selectedRow, 0).toString();
        String fullName = model.getValueAt(selectedRow, 1).toString();
        String mobile = model.getValueAt(selectedRow, 2).toString();
        String gender = model.getValueAt(selectedRow, 3).toString();
        String ageStatus = model.getValueAt(selectedRow, 4).toString();

        // --- Divide Full Name into First Name and Last Name ---
        String fname = "";
        String lname = "";

        if (fullName != null && !fullName.trim().isEmpty()) {
            String[] nameParts = fullName.trim().split("\\s+", 2);
            fname = nameParts[0];
            lname = (nameParts.length > 1) ? nameParts[1] : "";
        }

        // --- Fill form fields ---
        customerRagisterNoLable.setText(customerId);
        firstNameTextField.setText(fname);
        lastNameTextField.setText(lname);
        mobileTextField.setText(mobile);
        genderComboBox.setSelectedItem(gender);
        ageComboBox.setSelectedItem(ageStatus);

        if (selectedRow != -1 && evt.getClickCount() == 2) {
            if (booking != null) {
                String custometID = String.valueOf(customerTable.getValueAt(selectedRow, 0));
                booking.getCustomerIdTextField().setText(customerId);
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(this, "Customer Id Not Set");
            }
        }

    }//GEN-LAST:event_customerTableMouseClicked

