    private void addBooking() {

        Transaction transaction = null;
        Session session = null;

        try {
            int confirm = JOptionPane.showConfirmDialog(
                    this,
                    "Do you want to add this booking?",
                    "Confirm Booking",
                    JOptionPane.YES_NO_OPTION
            );

            if (confirm != JOptionPane.YES_OPTION) {
                return;
            }

            String customerId = selectCustomerIdTextField.getText().trim();
            String bookingStatusName = (String) bookingStatusComboBox.getSelectedItem();
            String workingStatusName = (String) workingStatusComboBox.getSelectedItem();

            if (customerId.isEmpty() || jDateChooser1.getDate() == null) {
                JOptionPane.showMessageDialog(this, "Please fill all required fields.");
                return;
            }

            if (bookingStatusName == null || workingStatusName == null
                    || bookingStatusName.equals("Select")
                    || workingStatusName.equals("Select")) {
                JOptionPane.showMessageDialog(this, "Please select Booking Status and Working Status.");
                return;
            }

            LocalDate bookingDate = jDateChooser1.getDate()
                    .toInstant()
                    .atZone(ZoneId.systemDefault())
                    .toLocalDate();

            LocalTime startTime = (LocalTime) bookingStartTimePicker.getTime();
            LocalTime endTime = (LocalTime) bookingEndTimePicker.getTime();

            if (!endTime.isAfter(startTime)) {
                JOptionPane.showMessageDialog(this, "End time must be after start time.");
                return;
            }

            session = HibernateUtil.getSessionFactory().openSession();
            transaction = session.beginTransaction();

            Customer customer = session.get(Customer.class, customerId);
            if (customer == null) {
                JOptionPane.showMessageDialog(this, "Invalid Customer ID.");
                transaction.rollback();
                return;
            }

            BookingStatus bookingStatus = session.createQuery(
                    "FROM BookingStatus WHERE booking_st = :st",
                    BookingStatus.class
            ).setParameter("st", bookingStatusName).uniqueResult();

            WorkingStatus workingStatus = session.createQuery(
                    "FROM WorkingStatus WHERE status = :st",
                    WorkingStatus.class
            ).setParameter("st", workingStatusName).uniqueResult();

            if (bookingStatus == null || workingStatus == null) {
                JOptionPane.showMessageDialog(this, "Invalid Booking or Working Status.");
                transaction.rollback();
                return;
            }

            // ✅ MAX 4 BOOKINGS CHECK
            Long overlapCount = session.createQuery(
                    "SELECT COUNT(b) FROM Booking b "
                    + "WHERE b.date = :date "
                    + "AND b.start_time < :end "
                    + "AND b.end_time > :start",
                    Long.class
            )
                    .setParameter("date", bookingDate)
                    .setParameter("start", startTime)
                    .setParameter("end", endTime)
                    .uniqueResult();

            if (overlapCount != null && overlapCount >= 4) {
                JOptionPane.showMessageDialog(this,
                        "Maximum 4 bookings allowed for this time slot.");
                transaction.rollback();
                return;
            }

            Booking booking = new Booking();
            booking.setId(IDGenerator.generateId("BKI", "Booking"));
            booking.setCustomer_id(customer);
            booking.setDate(bookingDate);
            booking.setStart_time(startTime);
            booking.setEnd_time(endTime);
            booking.setBooking_status_id(bookingStatus);
            booking.setWorking_status_id(workingStatus);

            session.save(booking);
            transaction.commit();

            JOptionPane.showMessageDialog(this, "Booking added successfully!");
            clearAllBookingFields();
            loadBookingTable();

        } catch (Exception e) {
            if (transaction != null && transaction.getStatus().canRollback()) {
                transaction.rollback();
            }
            JOptionPane.showMessageDialog(this, "Error saving booking: " + e.getMessage());
            e.printStackTrace();
        } finally {
            if (session != null) {
                session.close();
            }
        }
    }

