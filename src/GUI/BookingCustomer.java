    private void loadBookingStatus() {
        try {
            session = HibernateUtil.getSessionFactory().openSession();

            CriteriaBuilder cb = session.getCriteriaBuilder();
            CriteriaQuery<BookingStatus> cq = cb.createQuery(BookingStatus.class
            );
            Root<BookingStatus> root = cq.from(BookingStatus.class
            );

            cq.select(root).where(cb.isNotNull(root.get("booking_st")))
                    .orderBy(cb.asc(root.get("id")));

            List<BookingStatus> bookingStatuses = session.createQuery(cq).getResultList();

            Vector<String> vector = new Vector<>();
            loadBookingStatusMap.clear();

            for (BookingStatus bookingStatus : bookingStatuses) {
                vector.add(bookingStatus.getBooking_st());
                loadBookingStatusMap.put(bookingStatus.getBooking_st(), String.valueOf(bookingStatus.getId()));
            }

            DefaultComboBoxModel model = new DefaultComboBoxModel(vector);
            bookingStatusComboBox.setModel(model);

            //  Automatically select “Male” if exists
            for (int i = 0; i < bookingStatusComboBox.getItemCount(); i++) {
                if ("Male".equalsIgnoreCase(bookingStatusComboBox.getItemAt(i).toString())) {
                    bookingStatusComboBox.setSelectedIndex(i);
                    break;
                }
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "DataBase Erro Occurred.", "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        } finally {
            if (session != null && session.isOpen()) {
                session.close();
            }
        }
    }

