    private void bookingTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_bookingTableMouseClicked
        // TODO add your handling code here:

        bookingButton.setEnabled(false);
        bookingUpdateButton.setEnabled(true);
        int selectedRow = bookingTable.getSelectedRow();
        if (selectedRow == -1) {
            return;
        }

        // Adjust index if sorting is active
        selectedRow = bookingTable.convertRowIndexToModel(selectedRow);

        DefaultTableModel model = (DefaultTableModel) bookingTable.getModel();

        // --- Extract data from table ---
        String bookingId = model.getValueAt(selectedRow, 0).toString();
        String customerId = model.getValueAt(selectedRow, 1).toString();
        String customerName = model.getValueAt(selectedRow, 2).toString();
        String bookingDate = model.getValueAt(selectedRow, 3).toString();
        String startTime = model.getValueAt(selectedRow, 4).toString();
        String endTime = model.getValueAt(selectedRow, 5).toString();
        String mobile = model.getValueAt(selectedRow, 6).toString();
        String bookingStatus = model.getValueAt(selectedRow, 7).toString();
        String workingStatus = model.getValueAt(selectedRow, 8).toString();

        // --- Fill form fields ---
        bookingIdLable.setText(bookingId);
        selectCustomerIdTextField.setText(customerId);
        bookingStatusComboBox.setSelectedItem(bookingStatus);
        workingStatusComboBox.setSelectedItem(workingStatus);

        // --- Set Date ---
        try {
            LocalDate date = LocalDate.parse(bookingDate);
            jDateChooser1.setDate(java.sql.Date.valueOf(date));
        } catch (Exception e) {
            System.err.println("Date parse error: " + e.getMessage());
        }

        // --- Set Time ---
        try {
            LocalTime start = LocalTime.parse(startTime);
            LocalTime end = LocalTime.parse(endTime);

            bookingStartTimePicker.setTime(start);
            bookingEndTimePicker.setTime(end);

        } catch (Exception e) {
            System.err.println("Time parse error: " + e.getMessage());
        }


    }//GEN-LAST:event_bookingTableMouseClicked

