    private void loadBookingTable() {

        try {
            session = HibernateUtil.getSessionFactory().openSession();

            // --- Fetch All Bookings ---
            List<Booking> bookingList = session.createQuery(
                    "FROM Booking b ORDER BY b.id ASC", Booking.class
            ).list();

            DefaultTableModel model = (DefaultTableModel) bookingTable.getModel();
            model.setRowCount(0);

            for (Booking b : bookingList) {

                String fullName = b.getCustomer_id().getFname()
                        + " " + b.getCustomer_id().getLname();

                Vector<Object> row = new Vector<>();
                row.add(b.getId());
                row.add(b.getCustomer_id().getId());
                row.add(fullName);
                row.add(b.getDate());
                row.add(b.getStart_time());
                row.add(b.getEnd_time());
                row.add(b.getCustomer_id().getMobile());
                row.add(b.getBooking_status_id().getBooking_st());
                row.add(b.getWorking_status_id().getStatus());

                model.addRow(row);
            }

            //Table Center
            DefaultTableCellRenderer centerRenderer = new DefaultTableCellRenderer();
            centerRenderer.setHorizontalAlignment(DefaultTableCellRenderer.CENTER);
            for (int i = 0; i < bookingTable.getColumnCount(); i++) {
                bookingTable.getColumnModel().getColumn(i).setCellRenderer(centerRenderer);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, " Error loading bookings: " + e.getMessage());
            e.printStackTrace();
        } finally {
            if (session != null) {
                session.close();
            }
        }
    }

    private void searchBookingTable() {

        DefaultTableModel model = (DefaultTableModel) bookingTable.getModel();
        TableRowSorter<DefaultTableModel> sorter = new TableRowSorter<>(model);
        bookingTable.setRowSorter(sorter);

        String searchText = bookingTableSearchTextField.getText().trim();

        if (searchText.isEmpty()) {
            sorter.setRowFilter(null);
        } else {
            sorter.setRowFilter(RowFilter.regexFilter(
                    "(?i)" + searchText,
                    0, // Booking ID
                    1, // Customer ID
                    2, // Customer Full Name
                    3, // Date
                    6, // Booking Status
                    7 // Working Status
            ));
        }
    }

    private void setupBackspaceKeyShortcut() {

        JRootPane rootPane = getRootPane();

        InputMap im = rootPane.getInputMap(JComponent.WHEN_IN_FOCUSED_WINDOW);
        ActionMap am = rootPane.getActionMap();

        // BACKSPACE key
        im.put(KeyStroke.getKeyStroke(KeyEvent.VK_BACK_SPACE, 0), "BACKSPACE_ACTION");

        am.put("BACKSPACE_ACTION", new AbstractAction() {
            @Override
            public void actionPerformed(ActionEvent e) {
                clearAllBookingFields(); // or any method you want
            }
        });
    }

    private void clearAllBookingFields() {

        bookingIdLable.setText("");
        selectCustomerIdTextField.setText("");

        bookingStatusComboBox.setSelectedIndex(0);
        workingStatusComboBox.setSelectedIndex(0);

        jDateChooser1.setDate(null);

        // Reset time pickers
        bookingStartTimePicker.setTime(LocalTime.of(0, 0)); // default start time
        bookingEndTimePicker.setTime(LocalTime.of(0, 0));  // default end time

        bookingButton.setEnabled(true);
        bookingUpdateButton.setEnabled(false);

        // Reload table (optional)
        loadBookingTable();
    }

