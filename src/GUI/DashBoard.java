    public void loadDashboardBookingTable() {

        try {
            session = HibernateUtil.getSessionFactory().openSession();

            // --- Fetch Today's Bookings ---
            List<Booking> bookingList = session.createQuery(
                    "FROM Booking b WHERE b.date = :today AND b.working_status_id.id = :statusId ORDER BY b.start_time ASC",
                    //FROM Booking b WHERE b.working_status_id.id = :statusId ORDER BY b.id ASC
                    Booking.class
            )
                    .setParameter("today", today)
                    .setParameter("statusId", 1)
                    .list();

            DefaultTableModel model
                    = (DefaultTableModel) dashboardBookingTable.getModel();
            model.setRowCount(0);

            for (Booking b : bookingList) {

                String fullName
                        = b.getCustomer_id().getFname() + " "
                        + b.getCustomer_id().getLname();

                model.addRow(new Object[]{
                    b.getId(),
                    b.getCustomer_id().getId(),
                    fullName,
                    b.getDate(),
                    b.getStart_time(),
                    b.getEnd_time(),
                    b.getCustomer_id().getMobile(),
                    b.getBooking_status_id().getBooking_st(),
                    b.getWorking_status_id().getStatus()
                });
            }

            //Table Center
            DefaultTableCellRenderer centerRenderer = new DefaultTableCellRenderer();
            centerRenderer.setHorizontalAlignment(DefaultTableCellRenderer.CENTER);
            for (int i = 0; i < dashboardBookingTable.getColumnCount(); i++) {
                dashboardBookingTable.getColumnModel().getColumn(i).setCellRenderer(centerRenderer);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Error loading bookings: " + e.getMessage()
            );
            e.printStackTrace();
        } finally {
            if (session != null) {
                session.close();
            }
        }
    }

    private void searchDBoardBookingTable() {
        DefaultTableModel model = (DefaultTableModel) dashboardBookingTable.getModel();
        TableRowSorter<DefaultTableModel> sorter = new TableRowSorter<>(model);
        dashboardBookingTable.setRowSorter(sorter);

        String searchText = dashboardSearchTextField.getText().trim();

        if (searchText.isEmpty()) {
            sorter.setRowFilter(null);
        } else {
            // Booking ID, Customer ID, Customer Name, Date, Mobile, Status
            sorter.setRowFilter(RowFilter.regexFilter(
                    "(?i)" + searchText,
                    0, 1, 2, 3, 6, 7, 8
            ));
        }
    }

    private void startLiveDateTime() {

        // --- Date (Set once) ---
        LocalDate today = LocalDate.now();
        dashboardDateLabel.setText(
                today.format(DateTimeFormatter.ofPattern("yyyy/MM/dd"))
        );

        // --- Time (Live) ---
        Timer timer = new Timer(1000, e -> {
            LocalTime now = LocalTime.now();
            dashboardTimeLabel.setText(
                    now.format(DateTimeFormatter.ofPattern("HH:mm:ss a"))
            );
        });
        timer.start();
    }

    public void loadTodayDashboardSummary() {

        Session session = null;

        try {
            session = HibernateUtil.getSessionFactory().openSession();

            LocalDate today = LocalDate.now();

            // -------------------------------
            // 1️⃣ Today Booking Count
            // -------------------------------
            Long bookingCount = session.createQuery(
                    "SELECT COUNT(b.id) FROM Booking b WHERE b.date = :today AND b.working_status_id.id = :statusId",
                    Long.class
            )
                    .setParameter("today", today)
                    .setParameter("statusId", 1)
                    .uniqueResult();

            todayBookingCountLabel.setText(
                    bookingCount == null ? "0" : bookingCount.toString()
            );

            // -------------------------------
            // 2️⃣ Today Income (Invoice Total)
            // -------------------------------
            Double todayIncome = session.createQuery(
                    "SELECT SUM(i.price) "
                    + "FROM Invoice i "
                    + "JOIN i.invoice_item_id ii "
                    + "JOIN ii.booking_id b "
                    + "WHERE b.date = :today",
                    Double.class
            )
                    .setParameter("today", today)
                    .uniqueResult();

            todayIncomeLabel.setText(
                    todayIncome == null ? "0.00" : String.format("%.2f", todayIncome)
            );

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Dashboard Load Error: " + e.getMessage());
            e.printStackTrace();
        } finally {
            if (session != null) {
                session.close();
            }
        }
    }

